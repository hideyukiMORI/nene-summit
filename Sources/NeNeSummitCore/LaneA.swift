enum LaneA {
    static func rows(_ index: Int) -> [String] {
        switch index {
        case 0:
            return rise()
        case 1:
            return ledge()
        case 2:
            return pit()
        case 3:
            return cross()
        default:
            return well()
        }
    }

    private static func rise() -> [String] {
        [
            "#..#######################",
            "#..#######################",
            "#.^#######################",
            "#@..######################",
            "##########################",
        ]
    }

    private static func ledge() -> [String] {
        [
            "..........................",
            ".........................#",
            ".........................#",
            "................^^.......#",
            "###################fff...#",
            "######################...#",
            "######################..@#",
            "##########################",
        ]
    }

    private static func pit() -> [String] {
        [
            "..........................",
            "..........................",
            "..........................",
            "..............^^.....$o@..",
            "########..################",
        ]
    }

    private static func cross() -> [String] {
        var rows: [String] = []
        var above = 0
        while above < 14 {
            rows.append(String(repeating: ".", count: 26))
            above += 1
        }
        rows.append("@.........................")
        rows.append("..........................")
        rows.append("................DDD.......")
        rows.append("..........................")
        rows.append("o$........................")
        rows.append("fff####^##################")
        return rows
    }

    private static func well() -> [String] {
        [
            "..........................",
            "#.........................",
            "#.........................",
            "#.......^^................",
            "#...fff###################",
            "#...######################",
            "#@..######################",
            "##########################",
        ]
    }
}
